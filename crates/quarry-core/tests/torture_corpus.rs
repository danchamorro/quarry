//! Deterministic seeded torture corpus verification against `quarry-core`.
//!
//! Invokes `scripts/generate-torture-corpus.py` into a temporary directory, verifies
//! manifest SHA-256 digests, and checks every generated fixture against `quarry-core`
//! using its typed expectation (`accept`, `reject(<error>)`, or `needs-confirmation`)
//! without coupling to internal adaptive checkpoint spacing.

use std::path::{Path, PathBuf};
use std::process::Command;

use quarry_core::{
    CompressedBootstrap, CompressionFormat, Encoding, IndexConfig, OpenOptions, QuarryError,
    Session, detect_compression,
};
use quarry_delimited::ParseErrorKind;

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("workspace root")
        .to_path_buf()
}

fn python_command() -> &'static str {
    if cfg!(windows) { "python" } else { "python3" }
}

fn parse_manifest_entries(manifest: &str) -> Vec<(String, String)> {
    // Minimal parser for the deterministic manifest.json generated by generate-torture-corpus.py
    // without adding a serde_json dev-dependency.
    let mut entries = Vec::new();
    let mut current_file: Option<String> = None;
    for raw_line in manifest.lines() {
        let line = raw_line.trim();
        if let Some(rest) = line.strip_prefix("\"file\": \"") {
            let value = rest.trim_end_matches(',').trim_end_matches('"').to_owned();
            current_file = Some(value);
        } else if let Some(rest) = line.strip_prefix("\"expect\": \"") {
            let expect = rest.trim_end_matches(',').trim_end_matches('"').to_owned();
            let file = current_file
                .take()
                .expect("manifest expect must follow file");
            entries.push((file, expect));
        }
    }
    entries
}

#[test]
fn generated_torture_corpus_matches_manifest_and_core_expectations() {
    let dir = tempfile::tempdir().unwrap();
    let script = repo_root()
        .join("scripts")
        .join("generate-torture-corpus.py");
    assert!(
        script.exists(),
        "missing generator script: {}",
        script.display()
    );

    let gen_status = Command::new(python_command())
        .arg(&script)
        .arg("--output-dir")
        .arg(dir.path())
        .status()
        .expect("failed to execute generate-torture-corpus.py");
    assert!(gen_status.success(), "generate-torture-corpus.py failed");

    let verify_status = Command::new(python_command())
        .arg(&script)
        .arg("--output-dir")
        .arg(dir.path())
        .arg("--verify")
        .status()
        .expect("failed to verify torture corpus");
    assert!(
        verify_status.success(),
        "torture corpus digest check failed"
    );

    let manifest_text = std::fs::read_to_string(dir.path().join("manifest.json")).unwrap();
    let entries = parse_manifest_entries(&manifest_text);
    assert_eq!(entries.len(), 11, "expected 11 torture corpus fixtures");

    for (file, expect) in entries {
        let path = dir.path().join(&file);
        assert!(path.exists(), "missing fixture {file}");

        match (file.as_str(), expect.as_str()) {
            ("valid-seeded-utf8-bom.csv", "accept") => {
                let session = Session::open(&path, OpenOptions::default()).unwrap();
                assert_eq!(session.encoding(), Encoding::Utf8);
                assert_eq!(session.dialect.delimiter, b',');

                let mut reference_last_row = None;
                for checkpoint_every in [1_u64, 7, 4096] {
                    let index = session
                        .start_indexing(IndexConfig {
                            chunk_bytes: 257,
                            checkpoint_every,
                            memory_budget_bytes: 2048,
                        })
                        .unwrap()
                        .wait()
                        .unwrap();
                    assert_eq!(index.indexed_rows(), 201); // header + 200 seeded rows
                    assert_eq!(index.maximum_width(), 4);

                    let head = session.read_rows(&index, 0, 1).unwrap();
                    assert_eq!(
                        head[0].fields,
                        vec![
                            b"id".to_vec(),
                            b"label".to_vec(),
                            b"payload".to_vec(),
                            b"flag".to_vec()
                        ]
                    );

                    let tail = session.read_rows(&index, 200, 1).unwrap();
                    assert_eq!(tail[0].fields[0], b"200");
                    if let Some(prev) = &reference_last_row {
                        assert_eq!(prev, &tail[0]);
                    } else {
                        reference_last_row = Some(tail[0].clone());
                    }
                }
            }
            ("valid-gzip.csv.gz", "accept") => {
                assert_eq!(
                    detect_compression(&path).unwrap(),
                    Some(CompressionFormat::Gzip)
                );
                let bootstrap =
                    CompressedBootstrap::open(&path, OpenOptions::default(), None, None).unwrap();
                assert_eq!(bootstrap.first_rows.len(), 3);
                assert_eq!(
                    bootstrap.first_rows[1].fields,
                    vec![b"1".to_vec(), b"ok".to_vec()]
                );
            }
            ("unsupported-zstd.csv.zst", "reject(CompressedFile)") => {
                assert!(matches!(
                    detect_compression(&path),
                    Err(QuarryError::CompressedFile { .. })
                ));
                assert!(matches!(
                    Session::open(&path, OpenOptions::default()),
                    Err(QuarryError::CompressedFile { .. })
                ));
            }
            ("malformed-bare-quote.csv", "reject(Parse(UnexpectedQuote))") => {
                match Session::open(&path, OpenOptions::default()).unwrap_err() {
                    QuarryError::Parse(err) => {
                        assert_eq!(err.kind, ParseErrorKind::UnexpectedQuote);
                        assert_eq!(err.offset, 7);
                    }
                    other => panic!("{file}: expected Parse(UnexpectedQuote), got {other:?}"),
                }
            }
            ("malformed-after-quote.csv", "reject(Parse(UnexpectedAfterQuote))") => {
                match Session::open(&path, OpenOptions::default()).unwrap_err() {
                    QuarryError::Parse(err) => {
                        assert_eq!(err.kind, ParseErrorKind::UnexpectedAfterQuote(b'x'));
                        assert_eq!(err.offset, 8);
                    }
                    other => panic!("{file}: expected Parse(UnexpectedAfterQuote), got {other:?}"),
                }
            }
            ("malformed-unterminated-quote.csv", "reject(Parse(UnterminatedQuote))") => {
                match Session::open(&path, OpenOptions::default()).unwrap_err() {
                    QuarryError::Parse(err) => {
                        assert_eq!(err.kind, ParseErrorKind::UnterminatedQuote);
                        assert_eq!(err.offset, 17);
                    }
                    other => panic!("{file}: expected Parse(UnterminatedQuote), got {other:?}"),
                }
            }
            ("malformed-bare-cr-after-quote.csv", "reject(Parse(ExpectedLfAfterCr))") => {
                match Session::open(&path, OpenOptions::default()).unwrap_err() {
                    QuarryError::Parse(err) => {
                        assert_eq!(err.kind, ParseErrorKind::ExpectedLfAfterCr);
                        assert_eq!(err.offset, 9);
                    }
                    other => panic!("{file}: expected Parse(ExpectedLfAfterCr), got {other:?}"),
                }
            }
            ("unsupported-utf32-bom.csv", "reject(Encoding)") => {
                assert!(matches!(
                    Session::open(&path, OpenOptions::default()),
                    Err(QuarryError::Encoding(_))
                ));
            }
            ("oversize-over-64mib.csv", "reject(RecordTooLarge)") => {
                let session = Session::open(
                    &path,
                    OpenOptions {
                        rows: 1,
                        delimiter: Some(b','),
                        ..OpenOptions::default()
                    },
                )
                .unwrap();
                let index = session
                    .start_indexing(IndexConfig::default())
                    .unwrap()
                    .wait()
                    .unwrap();
                assert_eq!(index.indexed_rows(), 2);
                assert!(matches!(
                    session.read_rows(&index, 1, 1),
                    Err(QuarryError::RecordTooLarge { limit: 67_108_864 })
                ));
            }
            ("needs-confirm-latin1-no-bom.csv", "needs-confirmation") => {
                // Auto mode must NOT silently guess Latin-1.
                let auto_session = Session::open(&path, OpenOptions::default()).unwrap();
                assert_eq!(auto_session.encoding(), Encoding::Utf8);
                assert!(std::str::from_utf8(&auto_session.first_rows[1].fields[0]).is_err());

                // Explicit confirmation decodes cleanly to UTF-8.
                let confirmed = Session::open_with_encoding(
                    &path,
                    OpenOptions::default(),
                    Some(Encoding::Latin1),
                )
                .unwrap();
                assert_eq!(confirmed.encoding(), Encoding::Latin1);
                assert_eq!(confirmed.first_rows[1].fields[0], "café".as_bytes());
                assert_eq!(confirmed.first_rows[1].fields[1], "naïve".as_bytes());
            }
            ("needs-confirm-utf16le-no-bom.csv", "needs-confirmation") => {
                // Auto mode must NOT silently guess non-BOM UTF-16.
                let auto_utf16 = Session::open(&path, OpenOptions::default()).unwrap();
                assert_eq!(auto_utf16.encoding(), Encoding::Utf8);

                // Explicit confirmation decodes cleanly.
                let confirmed = Session::open_with_encoding(
                    &path,
                    OpenOptions::default(),
                    Some(Encoding::Utf16Le),
                )
                .unwrap();
                assert_eq!(confirmed.encoding(), Encoding::Utf16Le);
                assert_eq!(confirmed.first_rows.len(), 2);
                assert_eq!(
                    confirmed.first_rows[1].fields,
                    vec![b"1".to_vec(), b"2".to_vec()]
                );
            }
            (other_file, other_expect) => {
                panic!("unhandled torture corpus fixture: {other_file} ({other_expect})")
            }
        }
    }
}
